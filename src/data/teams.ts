// Helper function to calculate team rating
function calculateTeamRating(
  members: [string, string, string, string]
): number {
  return members.reduce((total, memberId) => {
    const character = CHARACTERS.find((c) => c.id === memberId);
    return total + (character?.rating || 0);
  }, 0);
}

